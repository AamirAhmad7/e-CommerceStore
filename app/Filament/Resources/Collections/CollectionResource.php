<?php

namespace App\Filament\Resources\Collections;

use App\Models\Collection;
use App\Models\Product;
use App\Models\ProductColor;
use App\Support\SeoFields;
use Filament\Actions\EditAction;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\SpatieMediaLibraryFileUpload;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Resources\Resource;
use Filament\Schemas\Components\Utilities\Get;
use Filament\Schemas\Components\Utilities\Set;
use Filament\Schemas\Schema;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\TernaryFilter;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class CollectionResource extends Resource
{
    protected static ?string $model = Collection::class;

    protected static ?string $recordTitleAttribute = 'title';

    public static function canViewAny(): bool
    {
        return Gate::allows('manage-commerce');
    }

    public static function canCreate(): bool
    {
        return Gate::allows('manage-commerce');
    }

    public static function canEdit(Model $record): bool
    {
        return Gate::allows('manage-commerce');
    }

    public static function canDelete(Model $record): bool
    {
        return false;
    }

    public static function form(Schema $schema): Schema
    {
        return $schema->components([
            SeoFields::section('title', 'introduction'),
            TextInput::make('title')->required()->maxLength(160)->live(onBlur: true)->afterStateUpdated(function (?string $state, ?string $old, Get $get, Set $set, ?Collection $record): void {
                if (! $record && (! $get('slug') || $get('slug') === Str::slug($old ?? ''))) {
                    $set('slug', Str::slug($state ?? ''));
                }
            }),
            TextInput::make('slug')->required()->maxLength(180)->regex('/^[a-z0-9]+(?:-[a-z0-9]+)*$/')->unique(ignoreRecord: true)->disabled(fn (?Collection $record) => $record?->is_published ?? false)->helperText('Suggested on creation. Title edits never change the link. Unpublish first if you deliberately need a different URL.'),
            Textarea::make('introduction')->label('Short introduction')->maxLength(1000)->rows(3)->columnSpanFull(),
            SpatieMediaLibraryFileUpload::make('cover')->collection('cover')->disk(config('store.media_disk'))->visibility('public')->image()->acceptedFileTypes(['image/jpeg', 'image/png', 'image/webp'])->maxSize(8192)->helperText('Optional. WebP previews are generated by the media worker.'),
            TextInput::make('cover_alt')->label('Cover image alt text')->maxLength(500),
            Toggle::make('is_published')->label('Published')->default(false)->helperText('Draft public URLs return 404. Preview is staff-only.'),
            Repeater::make('items')->label('Products in display order')->relationship('items')->orderColumn('sort_order')->defaultItems(0)->reorderableWithButtons()->addActionLabel('Add product')->columnSpanFull()->schema([
                Select::make('product_id')->label('Product (search name or SKU)')->required()->searchable()->distinct()->disableOptionsWhenSelectedInSiblingRepeaterItems()
                    ->getSearchResultsUsing(fn (string $search) => Product::where(fn ($q) => $q->where('name', 'like', '%'.$search.'%')->orWhereHas('variants', fn ($v) => $v->where('sku', 'like', '%'.$search.'%')))->limit(40)->pluck('name', 'id')->all())
                    ->getOptionLabelUsing(fn ($value) => Product::find($value)?->name)->rules([Rule::exists('products', 'id')->whereNull('deleted_at')])
                    ->live()->afterStateUpdated(fn (Set $set) => $set('featured_color_id', null)),
                Select::make('featured_color_id')->label('Featured color (optional)')->placeholder('Automatic eligible color')
                    ->options(fn (Get $get) => ProductColor::where('product_id', $get('product_id'))->orderBy('sort_order')->orderBy('id')->pluck('name', 'id')->all())
                    ->rules(fn (Get $get) => [Rule::exists('product_colors', 'id')->where('product_id', $get('product_id'))])->helperText('An inactive color falls back to the normal eligible color. A color without photos stays photo-less.'),
            ]),
        ]);
    }

    public static function table(Table $table): Table
    {
        return $table->columns([TextColumn::make('title')->searchable(), TextColumn::make('slug')->searchable(), TextColumn::make('is_published')->label('Publication')->formatStateUsing(fn ($state) => $state ? 'Published' : 'Draft')->badge(), TextColumn::make('items_count')->counts('items')->label('Selected products')])->filters([TernaryFilter::make('is_published')->label('Published')])->recordActions([EditAction::make()]);
    }

    public static function getPages(): array
    {
        return ['index' => Pages\ListCollections::route('/'), 'create' => Pages\CreateCollection::route('/create'), 'edit' => Pages\EditCollection::route('/{record}/edit')];
    }
}
